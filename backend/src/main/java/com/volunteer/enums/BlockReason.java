package com.volunteer.enums;

/**
 * 在途单被停在「能力校验失败」的原因。
 * 门槛收紧、证书过期、活动散场三类闸门互相独立，
 * 只有造成阻塞的那一类条件解除后才允许回到被卡前节点。
 */
public enum BlockReason {

    /** 未被阻塞（正常在途/已批完） */
    NONE,

    /** 岗位技能/证书/时长门槛改写后复核失败 */
    THRESHOLD,

    /** 岗位所需证书过期或缺失（证件时效闸门） */
    CERT,

    /** 活动已散场（状态结束或已过结束时间） */
    ACTIVITY
}
